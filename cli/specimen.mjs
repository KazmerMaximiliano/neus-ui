import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import { CONFIG_FILE, SYSTEM_CSS_FILE } from "./neus.consts.mjs";
import { PACKAGE_ROOT, importPath, readJson } from "./neus.utils.mjs";

const HELP = `Usage: npx neus specimen

Writes a page that shows the active system (or the derived system) in light and dark:
type scale, palette and surfaces, buttons beside fields, fields, alerts, cards, avatars
and section tones. Then run npx neus shot on the route it prints. Run it again after
changing the system or the palette; the files it writes are generated.

Options:
  -h, --help   Show this help`;

const header = "// Generated by `npx neus specimen`; run it again to update, delete it when done.\n";
const src = (root, dir) => existsSync(path.join(root, "src")) ? `src/${dir}` : dir;

/** The specimen component plus the route file the framework needs, and the route to capture. */
export const specimenFiles = (root, config) => {
  const derived = config.derivedSystem && existsSync(path.join(root, config.derivedSystem));
  const name = derived
    ? (readFileSync(path.join(root, config.derivedSystem), "utf8").match(/^name:\s*["']?(.+?)["']?\s*$/m)?.[1] ?? "Derived system")
    : config.designSystem;
  const component = (dir) => ({
    file: `${dir}/NeusSpecimen.tsx`,
    content: readFileSync(path.join(PACKAGE_ROOT, "cli/templates/NeusSpecimen.tsx"), "utf8")
      .replace("{{DESIGN_SYSTEM}}", config.designSystem)
      .replace("{{NAME}}", name.replace(/"/g, "'"))
      // Hex colors only, so the JSON needs no escaping inside the single-quoted string.
      .replace("{{COLORS}}", JSON.stringify(config.colors ?? {})),
  });

  if (config.rendering === "spa") {
    const styles = path.join(root, config.paths.styles);
    const entryDir = path.join(root, "src/neus");
    const css = [...(config.derivedSystem ? [SYSTEM_CSS_FILE] : []), "neus.overrides.css"]
      .map((file) => `import "${importPath(entryDir, path.join(styles, file))}";\n`).join("");
    const indexHtml = path.join(root, "index.html");
    // The project's index.html keeps its fonts and meta; only the entry script and title change.
    const html = existsSync(indexHtml)
      ? readFileSync(indexHtml, "utf8").replace(/<script type="module" src="[^"]+"><\/script>/, '<script type="module" src="/src/neus/specimen.tsx"></script>')
        .replace(/<title>[\s\S]*?<\/title>/, "<title>neus specimen</title>")
      : '<!doctype html>\n<html>\n  <head>\n    <meta charset="UTF-8" />\n    <title>neus specimen</title>\n  </head>\n  <body>\n' +
        '    <div id="root"></div>\n    <script type="module" src="/src/neus/specimen.tsx"></script>\n  </body>\n</html>\n';
    return {
      route: "/neus-specimen.html",
      files: [
        component("src/neus"),
        { file: "src/neus/specimen.tsx", content: `${header}import { createRoot } from "react-dom/client";\nimport "neus-ui/dist/neus-ui.css";\n${css}` +
          `import { NeusRoot } from "./NeusRoot";\nimport { NeusSpecimen } from "./NeusSpecimen";\n\n` +
          `createRoot(document.getElementById("root")!).render(<NeusRoot><NeusSpecimen /></NeusRoot>);\n` },
        { file: "neus-specimen.html", content: html },
      ],
    };
  }
  if (config.framework === "next" && config.rendering === "rsc") {
    const dir = `${existsSync(path.join(root, "src/app")) ? "src/app" : "app"}/neus-specimen`;
    return {
      route: "/neus-specimen",
      files: [component(dir), { file: `${dir}/page.tsx`, content: `${header}import { NeusSpecimen } from "./NeusSpecimen";\n\n` +
        "export default function NeusSpecimenPage() {\n  return <NeusSpecimen />;\n}\n" }],
    };
  }
  if (config.framework === "next") {
    const pages = existsSync(path.join(root, "src/pages")) ? "src/pages" : "pages";
    const dir = src(root, "neus");
    return {
      route: "/neus-specimen",
      files: [component(dir), { file: `${pages}/neus-specimen.tsx`,
        content: `${header}import { NeusSpecimen } from "${importPath(path.join(root, pages), path.join(root, dir, "NeusSpecimen"))}";\n\n` +
          "export default function NeusSpecimenPage() {\n  return <NeusSpecimen />;\n}\n" }],
    };
  }
  if (config.rendering === "islands") {
    return {
      route: "/neus-specimen",
      files: [component("src/neus"), { file: "src/pages/neus-specimen.astro",
        content: `---\n${header}import NeusLayout from "../layouts/NeusLayout.astro";\nimport { NeusSpecimen } from "../neus/NeusSpecimen";\n---\n\n` +
          '<NeusLayout title="neus specimen">\n  <NeusSpecimen />\n</NeusLayout>\n' }],
    };
  }
  // React Router, TanStack Start and other routers: the route is one line in the project's own config.
  const dir = config.framework === "tanstack-start" ? "src/neus" : "app/neus";
  return {
    route: "/neus-specimen",
    files: [component(dir)],
    note: `Add a route at /neus-specimen that renders <NeusSpecimen /> from ${dir}/NeusSpecimen.tsx.`,
  };
};

export const run = async (argv, root = process.cwd()) => {
  const { values } = parseArgs({ args: argv, options: { help: { type: "boolean", short: "h" } } });
  if (values.help) {
    process.stdout.write(`${HELP}\n`);
    return 0;
  }
  const config = readJson(path.join(root, CONFIG_FILE));
  if (!config) throw new Error(`No ${CONFIG_FILE} here. Run npx neus init first.`);
  const { files, route, note } = specimenFiles(root, config);
  for (const { file, content } of files) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    writeFileSync(path.join(root, file), content);
  }
  process.stdout.write([`Wrote ${files.map(({ file }) => file).join(", ")}.`, ...(note ? [note] : []),
    `Look at it with: npx neus shot ${route}`].join("\n") + "\n");
  return 0;
};
