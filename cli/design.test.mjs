import { mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import * as core from "../src/design.ts";
import { buildDesign, tokenSets } from "./design.mjs";
import { PACKAGE_ROOT } from "./neus.utils.mjs";

const css = readdirSync(path.join(PACKAGE_ROOT, "src"), { recursive: true }).filter((file) => file.endsWith(".css"))
  .map((file) => readFileSync(path.join(PACKAGE_ROOT, "src", file), "utf8")).join("\n");

const SECTIONS = ["Overview", "Colors", "Typography", "Layout", "Elevation & Depth", "Shapes", "Components", "Do's and Don'ts"]
  .map((name) => `## ${name}\n\nText.\n`).join("\n");
const derived = (extension) => `---
version: alpha
name: Monte
description: Forest and cream, serif display, square controls.
colors:
  ground: "#fbf7ef"
typography:
  display:
    fontFamily: '"Fraunces", serif'
rounded:
  control: 6px
spacing:
  step: 4px
components: {}
x-neus:
${extension}
---

# Monte

${SECTIONS}`;

const project = (document, config = {}) => {
  const root = mkdtempSync(path.join(tmpdir(), "neus-design-"));
  mkdirSync(path.join(root, "src/styles"), { recursive: true });
  mkdirSync(path.join(root, "design/system"), { recursive: true });
  writeFileSync(path.join(root, "neus.config.json"), JSON.stringify({
    framework: "vite", rendering: "spa", designSystem: "neus", derivedSystem: "design/system/DESIGN.md", colorScheme: "light",
    colors: {}, language: "es", brand: null, paths: { styles: "src/styles" }, ...config,
  }));
  if (document) writeFileSync(path.join(root, "design/system/DESIGN.md"), document);
  return root;
};

const MONTE = `  extends: neus
  tokens:
    base:
      --font-display: "{typography.display.fontFamily}"
      --radius-default: "{rounded.control}"
    light:
      --color-surface: "{colors.ground}"
    dark:
      --color-surface: "#1b1a16"
  recipes:
    button:
      base:
        --button-radius: "{rounded.control}"
        --button-label-transform: none`;

describe("neus design build", () => {
  it("compiles tokens and recipes under the base system's attribute, light and dark", () => {
    const root = project(derived(MONTE));
    const result = buildDesign(root, core, css);
    expect(result).toMatchObject({ file: "src/styles/neus.system.css", base: "neus", name: "Monte", wired: false });
    const output = readFileSync(path.join(root, "src/styles/neus.system.css"), "utf8");
    expect(output).toContain('[data-design-system="neus"] {\n  --font-display: "Fraunces", serif;\n  --radius-default: 6px;\n  --button-radius: 6px;');
    expect(output).toContain('[data-design-system="neus"][data-color-scheme="light"] {\n  --color-surface: #fbf7ef;\n}');
    expect(output).toContain('[data-design-system="neus"][data-color-scheme="dark"] {\n  --color-surface: #1b1a16;\n}');
    expect(output).toMatch(/^\/\* Monte: derived from neus\. Generated by npx neus design build/);
  });

  it("reports whether the root already imports the compiled file", () => {
    const root = project(derived(MONTE));
    writeFileSync(path.join(root, "src/main.tsx"), 'import "./styles/neus.system.css";\n');
    expect(buildDesign(root, core, css).wired).toBe(true);
  });

  it.each([
    ["a palette", "  extends: neus\n  palette:\n    light:\n      primary: \"#2f5d3a\"", "npx neus init --primary"],
    ["an id", "  extends: neus\n  id: monte", "no id or foundations"],
    ["an unknown base", "  extends: bootstrap", "x-neus.extends must be one of"],
    ["an unknown token", "  extends: neus\n  tokens:\n    base:\n      --button-radios: 6px", "--button-radios is not a neus-ui token"],
    ["a palette variable", "  extends: neus\n  tokens:\n    base:\n      --color-primary: \"#2f5d3a\"", "is a palette variable"],
    ["a scheme token in base", "  extends: neus\n  tokens:\n    base:\n      --color-surface: \"#fbf7ef\"", "set it under light and dark"],
    ["an unknown recipe family", "  extends: neus\n  recipes:\n    carousel:\n      base:\n        --x: 1px", "unknown key carousel"],
  ])("rejects %s", (_, extension, message) => {
    expect(() => buildDesign(project(derived(extension)), core, css)).toThrow(message);
  });

  it("asks for init when the base does not match, and for the skill when the file is missing", () => {
    expect(() => buildDesign(project(derived("  extends: carbon")), core, css)).toThrow("Run npx neus init --base carbon");
    expect(() => buildDesign(project(null), core, css)).toThrow("does not exist yet");
    expect(() => buildDesign(project(derived(MONTE), { derivedSystem: null }), core, css)).toThrow("uses the neus system as it is");
  });

  it("reads minified selectors from the published stylesheet", () => {
    const sets = tokenSets("[data-design-system=carbon]{--a:1px}[data-design-system=carbon][data-color-scheme=dark]{--b:2px}" +
      "[data-design-system=vercel][data-color-scheme=dark]{--c:3px}[data-color-scheme=dark]{--d:4px}", "carbon");
    expect([...sets.known].sort()).toEqual(["--a", "--b", "--c", "--d"]);
    expect([...sets.schemeDependent].sort()).toEqual(["--b", "--d"]);
  });
});
